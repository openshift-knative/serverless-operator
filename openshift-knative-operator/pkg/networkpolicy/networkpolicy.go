// Package networkpolicy provides builders for the operand NetworkPolicies
// that isolate the namespaces managed by the OpenShift Serverless Operator
// (knative-serving, knative-serving-ingress, knative-eventing) with a
// default-deny baseline plus tailored allow rules.
//
// The policies are generated by the operator at reconcile time (they are
// operand policies, not OLM-managed bundle resources) and are gated by the
// DisableGenerationAnnotation opt-out on the KnativeServing/KnativeEventing CR.
package networkpolicy

import (
	"context"
	"errors"
	"fmt"

	mf "github.com/manifestival/manifestival"
	corev1 "k8s.io/api/core/v1"
	networkingv1 "k8s.io/api/networking/v1"
	apierrors "k8s.io/apimachinery/pkg/api/errors"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/apimachinery/pkg/apis/meta/v1/unstructured"
	"k8s.io/apimachinery/pkg/util/intstr"
	"k8s.io/client-go/kubernetes"
	"k8s.io/client-go/kubernetes/scheme"
	"k8s.io/utils/ptr"
)

const (
	// DisableGenerationAnnotation is the opt-out annotation for the operand
	// NetworkPolicies on the KnativeServing/KnativeEventing CR. Generation
	// is enabled by default.
	DisableGenerationAnnotation = "serverless.openshift.io/disable-network-policies-generation"

	// ManagedByLabel marks every NetworkPolicy generated by this package so
	// they can be deleted again when generation is disabled via the
	// DisableGenerationAnnotation.
	ManagedByLabel = "serverless.openshift.io/network-policy"

	// apiServerPort and apiServerPortExternal allow the API server endpoints:
	// 443 is the in-cluster kubernetes service, 6443 the external endpoint
	// (e.g. on HyperShift the API lives outside the cluster network).
	apiServerPort int32 = 443
	//nolint:gosec // no credential, just a port number
	apiServerPortExternal int32 = 6443

	// monitoringPort is the kube-rbac-proxy secure metrics port scraped by
	// the cluster-monitoring prometheus (see pkg/monitoring).
	monitoringPort int32 = 8444
)

// DenyAll builds a default-deny policy blocking both ingress and egress for
// every pod in the namespace. Further policies add the required allows.
func DenyAll(name, namespace string) networkingv1.NetworkPolicy {
	return networkingv1.NetworkPolicy{
		ObjectMeta: metav1.ObjectMeta{
			Name:      name,
			Namespace: namespace,
			Labels:    managedLabels(),
		},
		Spec: networkingv1.NetworkPolicySpec{
			PodSelector: metav1.LabelSelector{},
			PolicyTypes: []networkingv1.PolicyType{
				networkingv1.PolicyTypeIngress,
				networkingv1.PolicyTypeEgress,
			},
		},
	}
}

// AllowSameNamespace builds a policy allowing all traffic between pods within
// the same namespace.
func AllowSameNamespace(name, namespace string) networkingv1.NetworkPolicy {
	return networkingv1.NetworkPolicy{
		ObjectMeta: metav1.ObjectMeta{
			Name:      name,
			Namespace: namespace,
			Labels:    managedLabels(),
		},
		Spec: networkingv1.NetworkPolicySpec{
			PodSelector: metav1.LabelSelector{},
			PolicyTypes: []networkingv1.PolicyType{
				networkingv1.PolicyTypeIngress,
				networkingv1.PolicyTypeEgress,
			},
			Ingress: []networkingv1.NetworkPolicyIngressRule{{
				From: []networkingv1.NetworkPolicyPeer{{PodSelector: &metav1.LabelSelector{}}},
			}},
			Egress: []networkingv1.NetworkPolicyEgressRule{{
				To: []networkingv1.NetworkPolicyPeer{{PodSelector: &metav1.LabelSelector{}}},
			}},
		},
	}
}

// AllowToAPIServer builds an egress policy allowing every pod in the
// namespace to reach the API server on TCP 443 and 6443. Port scoping is the
// only portable restriction: the API endpoint IP is cluster-specific
// (external on HyperShift), so any-address ipBlocks are intentional here.
func AllowToAPIServer(name, namespace string) networkingv1.NetworkPolicy {
	return networkingv1.NetworkPolicy{
		ObjectMeta: metav1.ObjectMeta{
			Name:      name,
			Namespace: namespace,
			Labels:    managedLabels(),
		},
		Spec: networkingv1.NetworkPolicySpec{
			PodSelector: metav1.LabelSelector{},
			PolicyTypes: []networkingv1.PolicyType{networkingv1.PolicyTypeEgress},
			Egress: []networkingv1.NetworkPolicyEgressRule{{
				To: AnyAddressPeers(),
				Ports: []networkingv1.NetworkPolicyPort{
					networkPolicyPort(corev1.ProtocolTCP, apiServerPort),
					networkPolicyPort(corev1.ProtocolTCP, apiServerPortExternal),
				},
			}},
		},
	}
}

// AllowToDNS builds an egress policy allowing every pod in the namespace to
// reach the cluster DNS (openshift-dns namespace) on UDP and TCP, ports 53
// and 5353.
func AllowToDNS(name, namespace string) networkingv1.NetworkPolicy {
	return networkingv1.NetworkPolicy{
		ObjectMeta: metav1.ObjectMeta{
			Name:      name,
			Namespace: namespace,
			Labels:    managedLabels(),
		},
		Spec: networkingv1.NetworkPolicySpec{
			PodSelector: metav1.LabelSelector{},
			PolicyTypes: []networkingv1.PolicyType{networkingv1.PolicyTypeEgress},
			Egress: []networkingv1.NetworkPolicyEgressRule{{
				To: []networkingv1.NetworkPolicyPeer{{
					NamespaceSelector: &metav1.LabelSelector{
						MatchLabels: map[string]string{
							"kubernetes.io/metadata.name": "openshift-dns",
						},
					},
				}},
				Ports: []networkingv1.NetworkPolicyPort{
					networkPolicyPort(corev1.ProtocolUDP, 53),
					networkPolicyPort(corev1.ProtocolTCP, 53),
					networkPolicyPort(corev1.ProtocolUDP, 5353),
					networkPolicyPort(corev1.ProtocolTCP, 5353),
				},
			}},
		},
	}
}

